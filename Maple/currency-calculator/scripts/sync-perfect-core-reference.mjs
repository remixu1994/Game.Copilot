import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const api = 'https://mxdm.dvg.cn/api/core-simulator.php';
const assetBase = 'https://mxdm.dvg.cn';

const localIds = {
  DarkKnight: 'dark-knight', SoulMaster: 'dawn-warrior', Aran: 'aran', Hero: 'hero', Paladin: 'paladin',
  DemonSlayer: 'demon-slayer', DemonAvenger: 'demon-avenger', Kaiser: 'kaiser', Adele: 'adele', Erel: 'erel',
  Bishop: 'bishop', FlameWizard: 'flame-wizard', Evan: 'evan', Luminous: 'luminous', ArchMageIL: 'ice-lightning',
  BattleMage: 'battle-mage', ArchMageFP: 'fire-poison', Kinesis: 'kinesis', Sia: 'sia', BowMaster: 'bowmaster',
  WindBreaker: 'wind-archer', Mercedes: 'mercedes', MarksMan: 'marksman', Pathfinder: 'pathfinder',
  WildHunter: 'wild-hunter', NightLord: 'night-lord', NightWalker: 'night-walker', Shadower: 'shadower',
  Phantom: 'phantom', Xenon: 'xenon', DualBlade: 'dual-blade', Captain: 'corsair', Striker: 'thunder-breaker',
  Buccaneer: 'buccaneer', EunWol: 'shade', Mechanic: 'mechanic', Cannoneer: 'cannoneer',
  AngelicBuster: 'angelic-buster', MukHyun: 'mo-xuan',
};

async function json(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  return response.json();
}

async function download(url, target) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, Buffer.from(await response.arrayBuffer()));
}

const { jobs } = await json(`${api}?action=jobs`);
const output = {};
const downloads = [];

for (const job of jobs) {
  const professionId = localIds[job.code];
  if (!professionId) continue;
  const { skills } = await json(`${api}?action=skills&job=${encodeURIComponent(job.code)}`);
  output[professionId] = skills.map((skill, index) => {
    const filename = `${skill.id}.png`;
    downloads.push({
      url: `${assetBase}${skill.icon}`,
      target: path.join(root, 'public', 'assets', 'skills', professionId, filename),
    });
    return {
      id: `${professionId}-${skill.id}`,
      name: skill.name,
      iconUrl: `/assets/skills/${professionId}/${filename}`,
      sortOrder: index,
    };
  });
}

for (let index = 0; index < downloads.length; index += 12) {
  await Promise.all(downloads.slice(index, index + 12).map((item) => download(item.url, item.target)));
}

const source = `// Generated by scripts/sync-perfect-core-reference.mjs.\n` +
  `export const referenceSkillSeeds = ${JSON.stringify(output, null, 2)} as const;\n`;
await writeFile(path.join(root, 'src', 'perfectCoreReferenceData.generated.ts'), source, 'utf8');

console.log(`Synced ${Object.keys(output).length} professions and ${downloads.length} skill icons.`);
